def expected_frames(out: Path, spec: RigSpec, sk: NativeSkeletonSpec, rig: dict[str, Any], poses, images, built,
                    manual, placement: Placement) -> dict[str, Any]:
    """SIMULATION of what Moho should render: the built layers (``pose_*``) and, for review, the same with the
    manual Smart Bone switches applied (``planned_*``). Labelled; never Moho evidence."""
    exp = out / "expected"
    exp.mkdir(parents=True, exist_ok=True)
    files: dict[str, Any] = {}
    font = ImageFont.load_default(size=max(18, spec.canvas_height // 40))
    rest_world = pose_world(spec, sk, {}, None)
    abd0 = rest_abduction(sk, rig)
    man_imgs = [(l, _canvas_image(l.rgba, placement)) for l in manual]
    cells, cells_p = [], []
    z_of = {id(im): i for i, (im, _) in enumerate(images)}
    for p in poses:
        world = pose_world(spec, sk, p["offsets_deg"], None)
        im = render(spec, images, world)
        rel = f"expected/pose_f{p['frame']:03d}_{p['id']}.png"
        im.save(out / rel, optimize=True)
        files[str(p["frame"])] = rel
        on = active_correctives([l for l, _ in man_imgs], driver_readings(sk, world, rest_world, abd0))
        under = [(mi, l.bone) for l, mi in man_imgs if l.name in on]
        planned = render(spec, under + images, world) if under else im
        relp = f"expected/planned_f{p['frame']:03d}_{p['id']}.png"
        planned.save(out / relp, optimize=True)
        files[f"planned_{p['frame']}"] = relp
        for target, img, tag in ((cells, im, "built layers"), (cells_p, planned, "with planned Smart Bone fills "
                                                                                   "(PENDING)")):
            cell = Image.new("RGBA", img.size, (236, 236, 236, 255))
            cell.alpha_composite(img)
            ImageDraw.Draw(cell).text((12, 10), f"SIMULATION (not Moho)\n{p['frame']}: {p['label']}\n{tag}",
                                      fill=(200, 0, 0, 255), font=font)
            target.append(cell)
    del z_of
    cw, ch = spec.canvas_width // 3, spec.canvas_height // 3
    for name, cl in (("SIMULATION_pose_sheet.png", cells), ("SIMULATION_planned_sheet.png", cells_p)):
        cols = 5
        sheet = Image.new("RGB", (cw * cols, ch * math.ceil(len(cl) / cols)), (255, 255, 255))
        for i, c in enumerate(cl):
            sheet.paste(c.convert("RGB").resize((cw, ch), Image.Resampling.LANCZOS), ((i % cols) * cw, (i // cols) * ch))
        sheet.save(exp / name, optimize=True)
        files["sheet" if "pose" in name else "planned_sheet"] = f"expected/{name}"
    return files


def load_hybrid(d: str | Path) -> tuple[RigSpec, dict[str, Any], dict[str, Any]]:
    d = Path(d)
    raw = json.loads((d / "rig_spec.json").read_text(encoding="utf-8"))
    man = json.loads((d / MANIFEST).read_text(encoding="utf-8"))
    return parse_spec(raw), raw, man
