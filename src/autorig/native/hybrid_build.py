"""Phase 4.2: the hybrid native rig package (`autorig native-hybrid`).

What the Mac needs to build the Phase 4.2 rig in Moho, from a character package:

- the hybrid layer set (``hybrid.assemble``): the Phase 4.1 layers with the limb roots split at their pivot planes
  and the arm chains drawn above the torso. Approved correctives are included; with ``review`` the pending
  clipped underlays (elbow / knee caps, shoe tops) are added, labelled pending. All are original or stored pixels,
  full canvas, unscaled, bound rigidly to one bone (operations Phase 4.0 ran natively);
- the ten Phase 4.2 test poses as rotation keys (frames 1-90); the torso lean (frame 80) is keyed by the verify
  script *after* reopening the saved file, so the reopened rig is shown to still work;
- the build script (the Phase 0 template under another name) and the verify script (reads the reopened rig, lists
  its actions, keys the lean);
- the Smart-Bone-switched native gap fills, exported per key for the manual Moho test (Switch layers and Smart Bone
  actions have no Lua evidence: they are never generated by guessing), and the Smart Bone plan;
- the artwork requests, the manual Moho tests, simulated expected frames (labelled SIMULATION) and a manifest.

Preparing the package is not native execution. ``autorig native-hybrid-verify`` checks the Mac evidence.
"""

