def test_store_is_append_only_tagged_and_character_independent(tmp_path):
    st = MotionReferenceStore(tmp_path / "lib")
    tr = synthetic_reference("shrug")
    rec = st.add("synthetic_shrug", tr, tr.meta)
    assert rec["v"] == 1 and rec["character_independent"] and "hand:palm_up (approved)" in rec["tags"]["required_artwork"]
    rec2 = st.add("synthetic_shrug", tr, tr.meta)
    assert rec2["v"] == 2 and st.versions("synthetic_shrug") == [1, 2]
    assert st.verify("synthetic_shrug") == []
    with pytest.raises(ValueError):
        st.add("Bad Id!", tr, tr.meta)
    with pytest.raises(ValueError, match="usage_permission"):
        st.add("x", tr, {"provenance": {"source": "s"}})
    st.annotate("synthetic_shrug", {"t0": 0.7, "label": "shoulders up"})
    assert st.get("synthetic_shrug")["annotations"][0]["label"] == "shoulders up"
    p = tmp_path / "lib" / "synthetic_shrug" / "v2" / "track.json"
    p.write_text(p.read_text().replace("1", "2", 1))
    assert st.verify("synthetic_shrug"), "tampering is detected"
    tw = synthetic_reference("walking")
    st.add("synthetic_walking", tw, tw.meta)
    assert [r["id"] for r in st.search(movement="locomotion")] == ["synthetic_walking"]
    assert st.search(supported_only=True) == []
    text = json.dumps(st.list())
    assert "schoolboy" not in text and "character_package" not in text


