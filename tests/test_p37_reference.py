def test_bvh_skeletal_import_projects_a_front_view():
    tr = bvh_track(BVH, meta=PERMIT)
    assert tr.frames == 3 and abs(tr.fps - 30.0) < 0.1
    # the subject's left (+X in BVH) appears on the image right; the right arm (Zrotation -90) lifts outward
    assert tr.p("shoulder_l")[0, 0] > tr.p("shoulder_r")[0, 0]
    an = ReferenceMotionAnalyzer().analyze(tr)
    with pytest.raises(ImportError_):
        bvh_track("HIERARCHY\nROOT X { OFFSET 0 0 0 CHANNELS 0 }\nMOTION\nFrames: 1\nFrame Time: 0.1\n\n")
    assert an["frames"] == 3


def test_quality_flags_side_view_and_poor_visibility():
    tr = synthetic_reference("pointing")
    q = ReferenceMotionImporter.quality(tr)
    assert q["view"] == "front" and q["usable"] and not q["flags"]
    side = LandmarkTrack(tr.fps, tr.data.copy(), tr.width, tr.height, {})
    from autorig.refmotion.track import J
    for s in ("r", "l"):  # collapse the shoulders/hips to a line: a side view
        side.data[:, J[f"shoulder_{s}"], 0] = tr.data[:, J["nose"], 0]
        side.data[:, J[f"hip_{s}"], 0] = tr.data[:, J["nose"], 0]
    side.data[:, :, 3] = 0.3
    q = ReferenceMotionImporter.quality(side)
    assert q["view"] == "side" and not q["usable"] and any("visibility" in f for f in q["flags"])


