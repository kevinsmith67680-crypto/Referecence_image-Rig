def test_fixture_provider_and_low_confidence_smoothing():
    base = synthetic_reference("pointing")
    noisy = base.data.copy()
    noisy[10, :, :2] += 80.0  # a wild low-confidence frame
    noisy[10, :, 3] = 0.1
    tr = FixtureProvider(lambda i: noisy[i]).estimate([np.zeros((10, 10, 3))] * base.frames, base.fps)
    from autorig.refmotion.analyze import smooth
    P, low = smooth(tr)
    assert low[10].all() and np.abs(P[10, :, :2] - base.data[10, :, :2]).max() < 20, "low confidence is down-weighted"


# -- analysis --------------------------------------------------------------------------------------------------
def test_analysis_extracts_angles_timing_and_accents():
    an = ReferenceMotionAnalyzer().analyze(synthetic_reference("pointing"))
    abd = np.array(an["channels"]["arm_r_abduction"])
    assert abd[0] == pytest.approx(8.0, abs=1.0) and abd.max() == pytest.approx(91.0, abs=3.0)
    acc = an["accents"]["arm_r_abduction"]
    assert acc["anticipation"] > 3.0 and acc["overshoot"] > 1.0, "the counter-move and overshoot are detected"
    assert any(h[1] - h[0] > 0.5 for h in an["timing"]["holds"]), "the pointing hold is found"
    assert not an["depth_segments"], "a lateral point stays in the image plane"
    head = np.array(an["channels"]["head"])
    assert head.max() > 3.0 and abs(np.array(an["channels"]["line_of_action"])).max() > 2.0


def test_analysis_detects_depth_motion():
    sh = ReferenceMotionAnalyzer().analyze(synthetic_reference("shrug"))
    assert {"forearm_r", "forearm_l"} <= set(sh["depth_segments"])
    assert np.array(sh["channels"]["clavicle_r"]).max() > 5.0, "shoulders rise"
    wk = ReferenceMotionAnalyzer().analyze(synthetic_reference("walking"))
    assert {"shin_r", "shin_l"} <= set(wk["depth_segments"])
    assert wk["coordination"] is not None and "contacts" in wk


# -- retargeting -----------------------------------------------------------------------------------------------
def test_retarget_keys_intensity_and_feasibility():
    R = ReferenceMotionRetargeter()
    tr = synthetic_reference("pointing")
    an = ReferenceMotionAnalyzer().analyze(tr)
    out = R.retarget(an, tr.meta)
    assert out["feasibility"]["class"] == "SUPPORTED" and 4 <= out["keys"] <= 30
    doc = out["performance"]
    hands = [k["hands"].get("r") for k in doc["base_keys"]]
    assert "pointing" in hands and "relaxed_standing" in hands, "the hand action follows the arm"
    half = R.retarget(an, tr.meta, intensity=0.5)
    peak = lambda d: max(k["params"]["arm_r_abduction"] for k in d["performance"]["base_keys"])
    assert peak(half) == pytest.approx(11.0 + 0.5 * (peak(out) - 11.0), abs=0.5)
    slow = R.retarget(an, tr.meta, timing_scale=2.0)
    assert slow["performance"]["base_keys"][-1]["t"] == pytest.approx(2 * doc["base_keys"][-1]["t"], abs=0.02)
    seg = R.retarget(an, tr.meta, segment=(0.4, 2.0))
    assert seg["performance"]["base_keys"][0]["t"] == 0.0 and seg["settings"]["segment"] == [0.4, 2.0]


def test_retarget_reports_depth_and_never_stretches():
    R = ReferenceMotionRetargeter()
    for name, cls in (("shrug", "REQUIRES_ALTERNATIVE_ARTWORK"), ("walking", "REQUIRES_NEW_VIEW")):
        tr = synthetic_reference(name)
        out = R.retarget(ReferenceMotionAnalyzer().analyze(tr), tr.meta)
        assert out["feasibility"]["class"] == cls
        assert all("not stretched" in i["handling"] or "not rendered" in i["handling"] for i in out["feasibility"]["items"])
        keys = out["performance"]["base_keys"]
        assert all(set(k["params"]) <= set(R.neutral) | {"contrapposto"} for k in keys), "angles only, no lengths"
    walk = R.retarget(ReferenceMotionAnalyzer().analyze(synthetic_reference("walking")), synthetic_reference("walking").meta)
    ks = walk["performance"]["base_keys"]
    assert max(abs(k["params"]["arm_r_abduction"] - 11.0) for k in ks) < 1.0, "depth arm swing is not faked in-plane"


