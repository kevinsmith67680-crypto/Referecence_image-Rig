@real
def test_revision_loop_is_bounded_and_never_approves(ev):
    from autorig.artistic.transitions import acting_test_keys
    from autorig.performance import scenarios, shoulders
    from autorig.performance.director import PerformanceDirector

    eng, vis = ev
    t = next(k.t for k in acting_test_keys() if k.label == "shrug") + 0.3
    n = PerformanceDirector(eng, vis, scenarios.acting_upgrade()).solve(0.0, render=True)
    ref = shoulders.measure(n["image"], n["solve"]["joints_posed"], n["pad"])
    perf = scenarios.acting_upgrade()
    for k in perf.base_keys:
        if k["label"].startswith("shrug"):
            k["params"].update({"clavicle_r": 13.0, "clavicle_l": 15.0})
    doc = perf.to_json()
    out = RevisionLoop(eng, vis, max_attempts=2).run(doc, t, {"shoulder_reference": ref, "shrug": True})
    assert out["original_untouched"] and doc == perf.to_json()
    assert out["approved"] is False and len(out["attempts"]) <= 2
    assert out["status"] == "PROPOSED_NEEDS_APPROVAL"
    kept = [a for a in out["attempts"] if a["result"] == "kept"]
    assert kept and all(a["after"] < a["before"] for a in kept)
    k = next(k for k in out["candidate"]["base_keys"] if k["label"].startswith("shrug"))
    assert k["params"]["clavicle_r"] < 13.0 or k["params"]["clavicle_l"] < 15.0


@real
def test_reference_ops_and_http(tmp_path):
    from fastapi.testclient import TestClient

    from autorig.editor.project import EditorProject, OpError
    from autorig.editor.server import create_app

    dst = tmp_path / "pkg"

    def ignore(d, names):
        skip = {"editor"}
        if Path(d).name == "natural_pose":
            skip |= {"poses", "legacy", "closeups", "performance", "artistic", "garments", "correctives", "motion",
                     "ik_switch", "hand_selection", "reference_motion"}
        return [n for n in names if n in skip]

    shutil.copytree(REAL_PKG, dst, ignore=ignore)
    lib = tmp_path / "motion_references"
    tr = synthetic_reference("pointing")
    MotionReferenceStore(lib).add("synthetic_pointing", tr, tr.meta)
    p = EditorProject(dst)
    p.submit({"type": "reference.select", "ref_id": "synthetic_pointing"})
    p.submit({"type": "reference.settings", "ref_id": "synthetic_pointing", "intensity": 0.8, "segment": [0.2, 2.4],
              "hand_actions": {"r": "pointing"}})
    with pytest.raises(OpError):
        p.submit({"type": "reference.settings", "ref_id": "synthetic_pointing", "intensity": 9})
    with pytest.raises(OpError):
        p.submit({"type": "reference.settings", "ref_id": "synthetic_pointing", "hand_actions": {"r": "teleport"}})
    p.submit({"type": "reference.annotate", "ref_id": "synthetic_pointing", "label": "hold", "t0": 1.2})
    p.submit({"type": "reference.preset.save", "ref_id": "synthetic_pointing", "name": "p1"})
    st = EditorProject(dst).state()["reference_motion"]
    assert st["selected"] == "synthetic_pointing" and st["settings"]["synthetic_pointing"]["intensity"] == 0.8
    assert st["presets"]["p1"]["settings"]["segment"] == [0.2, 2.4] and st["annotations"]["synthetic_pointing"]
    import os
    os.environ["AUTORIG_MOTION_LIBRARY"] = str(lib)
    try:
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            c = TestClient(create_app(dst))
        info = c.get("/api/reference").json()
        assert [r["id"] for r in info["library"]] == ["synthetic_pointing"]
        assert c.get("/api/reference/synthetic_pointing/frame.png", params={"i": 20}).status_code == 200
        rt = c.post("/api/reference/synthetic_pointing/retarget", json={}).json()
        assert rt["feasibility"]["class"] == "SUPPORTED" and rt["settings"]["intensity"] == 0.8
        assert c.post("/api/op", json={"type": "performance.set", "doc": rt["performance"]}).status_code == 200
        cr = c.post("/api/reference/synthetic_pointing/critique", json={"t": 1.3}).json()
        assert cr["approves"] is False
        bad = c.post("/api/reference/import", json={"ref_id": "x1", "name": "a.json", "data_b64": "e30=",
                                                     "source": "s"})
        assert bad.status_code == 422, "no permission statement -> rejected"
    finally:
        os.environ.pop("AUTORIG_MOTION_LIBRARY", None)
